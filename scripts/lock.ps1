# Regenerates requirements.lock from pyproject.toml in a clean temporary venv.
# Usage: .\scripts\lock.ps1   (requires the Python launcher with 3.13)
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("ea-lock-" + [guid]::NewGuid())
try {
    py -3.13 -m venv "$tmp"
    $py = Join-Path $tmp "Scripts\python.exe"
    & "$py" -m pip install --quiet --upgrade pip
    & "$py" -m pip install --quiet "$repo[dev]"
    if ($LASTEXITCODE -ne 0) { throw "pip install failed" }
    $lines = & "$py" -m pip freeze --exclude-editable | Where-Object { $_ -notmatch '^exterior[-_]agent' }
    $header = "# Generated by scripts/lock.ps1 from pyproject.toml (Python 3.13). Do not edit by hand."
    Set-Content -Path (Join-Path $repo "requirements.lock") -Value (@($header) + $lines) -Encoding ascii
    Write-Host "requirements.lock updated ($($lines.Count) packages)"
} finally {
    Remove-Item -Recurse -Force "$tmp" -ErrorAction SilentlyContinue
}
